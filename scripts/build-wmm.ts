import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Converts NOAA's WMM2025.COF into the typed constant src/lib/sweep/wmm2025.ts.
const root = fileURLToPath(new URL('..', import.meta.url));
const lines = readFileSync(`${root}data/wmm/WMM2025.COF`, 'utf8').split(/\r?\n/);
const header = lines[0].trim().split(/\s+/);
const epoch = Number(header[0]);
const rows: string[] = [];
for (const line of lines.slice(1)) {
  const f = line.trim().split(/\s+/);
  if (f.length !== 6) continue; // skips blank and 9999... terminator lines
  const [n, m, g, h, gDot, hDot] = f.map(Number);
  if ([n, m, g, h, gDot, hDot].some((v) => !Number.isFinite(v))) throw new Error(`bad COF row: ${line}`);
  rows.push(`    { n: ${n}, m: ${m}, g: ${g}, h: ${h}, gDot: ${gDot}, hDot: ${hDot} },`);
}
if (rows.length !== 90) throw new Error(`expected 90 coefficient rows, got ${rows.length}`);
const src = `// Generated by scripts/build-wmm.ts from data/wmm/WMM2025.COF - do not edit.
export interface WmmCoefficient {
  n: number;
  m: number;
  g: number;
  h: number;
  gDot: number;
  hDot: number;
}

export const WMM2025: { epoch: number; coefficients: WmmCoefficient[] } = {
  epoch: ${epoch},
  coefficients: [
${rows.join('\n')}
  ],
};
`;
writeFileSync(`${root}src/lib/sweep/wmm2025.ts`, src);
console.log(`wmm2025.ts: epoch ${epoch}, ${rows.length} coefficients`);
